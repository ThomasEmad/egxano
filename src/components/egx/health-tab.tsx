"use client"

import { useQuery } from "@tanstack/react-query"
import { Radar, RadarChart, PolarGrid, PolarAngleAxis, PolarRadiusAxis, ResponsiveContainer } from "recharts"
import { AlertTriangle, HeartPulse, Lock } from "lucide-react"
import { Badge } from "@/components/ui/badge"
import { Button } from "@/components/ui/button"
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card"
import { Progress } from "@/components/ui/progress"
import { Skeleton } from "@/components/ui/skeleton"
import { DataStateBadge } from "@/components/brand/data-trust"
import { useI18n } from "@/lib/i18n"
import { useSubscriptionGate } from "@/lib/client/subscription-gate"
import { formatEgp, formatPercent, formatRatio } from "@/lib/financial/units"

type ScoreComponent = { key: string; score: number | null; inputs: { label: string; value: number | null; unit: string }[] }
type ScoresData = {
  overall: number | null
  components: ScoreComponent[]
  valuation: {
    price: number | null; pe: number | null; pb: number | null
    sectorMedianPe: number | null; sectorMedianPb: number | null
    peDiscountPct: number | null; pbDiscountPct: number | null
    verdict: "undervalued" | "fair" | "expensive" | "no-price" | null
  } | null
}

const scoreColor = (v: number | null) =>
  v === null ? "text-muted-foreground" : v >= 70 ? "text-success" : v >= 40 ? "text-warning" : "text-destructive"

const LABELS: Record<string, { en: string; ar: string }> = {
  profitability: { en: "Profitability", ar: "الربحية" },
  leverage: { en: "Leverage", ar: "الرفع المالي" },
  cash: { en: "Cash quality", ar: "جودة النقد" },
}

/** Input labels generated by the scores engine (English) → Arabic. */
const INPUT_LABELS_AR: Record<string, string> = {
  "Net margin": "هامش صافي الربح",
  ROE: "العائد على حقوق الملكية",
  ROA: "العائد على الأصول",
  "Debt / Equity": "الدين إلى حقوق الملكية",
  "Operating cash flow": "التدفق النقدي التشغيلي",
  "Net profit": "صافي الربح",
}

function inputLabel(label: string, ar: boolean): string {
  if (!ar) return label
  return INPUT_LABELS_AR[label] ?? label
}

function inputValue(value: number | null, unit: string, ar: boolean): string {
  if (value === null) return ar ? "غير متاح" : "not available"
  if (unit === "PERCENT") return formatPercent(value)
  if (unit === "RATIO") return formatRatio(value)
  return formatEgp(value)
}

export function HealthTab({ companyId }: { companyId: string }) {
  const { lang } = useI18n()
  const ar = lang === "ar"
  const { data, isLoading, isError, refetch } = useQuery({
    queryKey: ["scores", companyId],
    queryFn: () => fetch(`/api/v1/companies/${companyId}/scores`).then((r) => (r.ok ? (r.json() as Promise<ScoresData>) : null)),
  })

  if (isError) {
    return (
      <Card className="border-border/60">
        <CardContent className="flex flex-col items-center justify-center gap-3 p-8 text-center">
          <AlertTriangle className="h-5 w-5 text-destructive" aria-hidden />
          <p className="text-sm text-muted-foreground">
            {ar
              ? "تعذر تحميل درجة المتانة المالية — تحقق من الاتصال وحاول مرة أخرى."
              : "Could not load the financial strength score — check your connection and try again."}
          </p>
          <Button variant="outline" size="sm" onClick={() => refetch()}>
            {ar ? "إعادة المحاولة" : "Retry"}
          </Button>
        </CardContent>
      </Card>
    )
  }
  if (isLoading || !data) return <Skeleton className="h-72 rounded-xl" />

  const overall = data.overall
  const radarData = data.components.map((c) => ({
    axis: LABELS[c.key] ? (ar ? LABELS[c.key].ar : LABELS[c.key].en) : c.key,
    score: c.score ?? 0,
  }))
  const available = data.components.filter((c) => c.score !== null).length
  const totalComponents = data.components.length

  return (
    <div className="space-y-4">
      {/* overall gauge */}
      <Card className="border-border/60">
        <CardContent className="flex flex-col gap-5 p-5 sm:flex-row sm:items-center">
          <div className="relative flex h-24 w-24 shrink-0 items-center justify-center">
            <svg viewBox="0 0 100 100" className="h-24 w-24 -rotate-90" aria-hidden>
              <circle cx="50" cy="50" r="42" fill="none" stroke="currentColor" strokeWidth="10" className="text-muted" />
              <circle
                cx="50" cy="50" r="42" fill="none" strokeWidth="10" strokeLinecap="round"
                className={scoreColor(overall).replace("text-", "stroke-")}
                strokeDasharray={`${((overall ?? 0) / 100) * 264} 264`}
              />
            </svg>
            <span className={`num absolute text-xl font-bold ${scoreColor(overall)}`}>{overall ?? "—"}</span>
          </div>
          <div className="min-w-0">
            <p className="flex flex-wrap items-center gap-2 text-sm font-semibold">
              <HeartPulse className="h-4 w-4 text-destructive" aria-hidden />
              {ar ? "درجة المتانة المالية" : "Financial strength score"}
              <DataStateBadge state="calculated" />
            </p>
            <p className="mt-1 max-w-md text-xs leading-relaxed text-muted-foreground">
              {ar
                ? "قراءة من 0 إلى 100 للمكوّنات المتاحة لهذه الشركة: الربحية، الرفع المالي، وجودة النقد."
                : "A 0–100 reading of the components available for this company: profitability, leverage and cash quality."}
            </p>
            <p className="mt-1 flex items-center gap-1.5 text-[11px] font-medium text-warning">
              <AlertTriangle className="h-3 w-3" aria-hidden />
              {ar
                ? `المكوّنات المتاحة: ${available} من ${totalComponents} — الدرجة تعكس ما نُشر فقط، وليست تقييمًا للشركة.`
                : `Components available: ${available} of ${totalComponents} — the score reflects what is published, not a rating of the company.`}
            </p>
            {data.valuation?.verdict === "no-price" ? (
              <p className="mt-1 text-[10px] text-muted-foreground">
                {ar
                  ? "لا توجد نقطة سعر مسجّلة، فالتقييم النسبي غير متاح."
                  : "No recorded price point, so relative valuation is unavailable."}
              </p>
            ) : null}
          </div>
        </CardContent>
      </Card>

      {/* component bars — free */}
      <div className="grid gap-3 sm:grid-cols-2">
        {data.components.map((c) => (
          <Card key={c.key} className="border-border/60 p-4">
            <div className="flex items-center justify-between">
              <span className="text-xs font-medium">{LABELS[c.key] ? (ar ? LABELS[c.key].ar : LABELS[c.key].en) : c.key}</span>
              <span className={`text-sm font-bold tabular ${scoreColor(c.score)}`}>{c.score ?? "—"}</span>
            </div>
            <Progress value={c.score ?? 0} className="mt-2 h-1.5" />
            <div className="mt-2 flex flex-wrap gap-x-3 gap-y-0.5 text-[10px] text-muted-foreground">
              {c.inputs.filter((i) => i.value !== null).map((i) => (
                <span key={i.label}>
                  {inputLabel(i.label, ar)}: <span className="tabular">{inputValue(i.value, i.unit, ar)}</span>
                </span>
              ))}
              {c.score === null ? (
                <span className="italic">
                  {ar
                    ? "غير متاح — لم تُنشر المدخلات اللازمة"
                    : "Not available — the required inputs were not published"}
                </span>
              ) : null}
            </div>
          </Card>
        ))}
      </div>

      {/* snowflake radar — Pro */}
      <Card className="border-border/60">
        <CardHeader className="pb-1">
          <CardTitle className="flex flex-wrap items-center gap-2 text-sm font-semibold">
            {ar ? "ندفة الثلج — الصورة الكاملة" : "Snowflake — the full picture"}
            <Badge variant="secondary" className="text-[9px]">{ar ? "بريميوم" : "Pro"}</Badge>
          </CardTitle>
        </CardHeader>
        <CardContent>
          <PremiumBody kind="radar" data={radarData as { axis?: string; score?: number; median?: number }[]} overall={overall} lang={lang} />
        </CardContent>
      </Card>

      {/* valuation detail — Pro */}
      {data.valuation && data.valuation.verdict !== "no-price" ? (
        <Card className="border-border/60">
          <CardHeader className="pb-1">
            <CardTitle className="text-sm font-semibold">
              {ar ? "تفاصيل التقييم مقابل القطاع" : "Valuation detail vs sector"}
              <Badge variant="secondary" className="ms-2 text-[9px]">{ar ? "بريميوم" : "Pro"}</Badge>
            </CardTitle>
          </CardHeader>
          <CardContent>
            <PremiumBody
              kind="valuation"
              lang={lang}
              data={[
                { k: ar ? "مضاعف الربحية P/E" : "P/E", v: data.valuation.pe, median: data.valuation.sectorMedianPe },
                { k: ar ? "مضاعف القيمة الدفترية P/B" : "P/B", v: data.valuation.pb, median: data.valuation.sectorMedianPb },
              ]}
              overall={overall}
            />
          </CardContent>
        </Card>
      ) : null}
    </div>
  )
}

function PremiumBody({ lang, data, overall, kind }: { lang: string; data: { axis?: string; k?: string; score?: number; v?: number | null; median?: number | null }[]; overall: number | null; kind: "radar" | "valuation" }) {
  const { isPremium } = useSubscriptionGate()
  const ar = lang === "ar"
  if (!isPremium) {
    return (
      <div className="flex flex-col items-center gap-2 rounded-xl border border-dashed border-warning/40 bg-warning/5 p-6 text-center">
        <Lock className="h-5 w-5 text-warning" aria-hidden />
        <p className="text-xs font-medium">
          {ar ? "الرسم التفصيلي متاح لمشتركي Pro" : "The full visual is available on Pro"}
        </p>
        <a href="/premium" className="text-xs text-primary underline underline-offset-2">
          {ar ? "اعرف إيه اللي في Pro" : "See what Pro includes"}
        </a>
        <p className="text-[10px] text-muted-foreground">
          {ar ? `الدرجة الإجمالية: ${overall ?? "—"}` : `Overall score: ${overall ?? "—"}`}
        </p>
      </div>
    )
  }
  if (kind === "radar") {
    return (
      <div className="h-72">
        <ResponsiveContainer width="100%" height="100%">
          <RadarChart data={data as { axis: string; score: number }[]} outerRadius="72%">
            <PolarGrid stroke="var(--border)" />
            <PolarAngleAxis dataKey="axis" tick={{ fontSize: 11, fill: "var(--muted-foreground)" }} />
            <PolarRadiusAxis domain={[0, 100]} tick={false} axisLine={false} />
            <Radar dataKey="score" stroke="var(--primary)" fill="var(--primary)" fillOpacity={0.35} />
          </RadarChart>
        </ResponsiveContainer>
      </div>
    )
  }
  return (
    <div className="space-y-3">
      {data.map((row) => (
        <div key={row.k} className="flex items-center justify-between gap-3 text-xs">
          <span className="font-medium">{row.k}</span>
          <span className="flex items-center gap-3 tabular">
            <span className="font-semibold">{row.v !== null && row.v !== undefined ? row.v.toFixed(1) + "x" : "—"}</span>
            <span className="text-muted-foreground">{ar ? "وسيط القطاع" : "sector median"}: {row.median !== null && row.median !== undefined ? row.median.toFixed(1) + "x" : "—"}</span>
          </span>
        </div>
      ))}
    </div>
  )
}
